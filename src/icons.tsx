import type { CSSProperties } from 'react'
type IconProps = { size?: number; className?: string; fill?: string; strokeWidth?: number; style?: CSSProperties }
function symbol(code: number) {
  return function MaterialIcon({ size = 18, className = '', fill, style }: IconProps) {
    return <span className={`material-symbol ${className}`} aria-hidden="true" style={{ fontSize: size, width: size, height: size, '--icon-fill': fill && fill !== 'none' ? 1 : 0, ...style } as CSSProperties}>{String.fromCodePoint(code)}</span>
  }
}
