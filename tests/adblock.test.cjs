const { test, before } = require('node:test');
const assert = require('node:assert/strict');
const blocker = require('../electron/adblock.cjs');
before(async () => blocker.setRules([
  '||ads.example.test^',
  '@@||ads.example.test/content.js$script',
  '/vast.xml$xmlhttprequest',
  'example.test##.advertisement',
]));
test('real ABP core blocks ad requests, with resource type and exceptions', () => {
  assert.equal(blocker.shouldBlock('https://ads.example.test/banner.js', 'script', 'https://example.test'), true);
  assert.equal(blocker.shouldBlock('https://ads.example.test/content.js', 'script', 'https://example.test'), false);
  assert.equal(blocker.shouldBlock('https://example.test/vast.xml', 'xhr', 'https://example.test'), true);
  assert.equal(blocker.shouldBlock('https://example.test/vast.xml', 'image', 'https://example.test'), false);
});
test('navigation and actual media remain usable without matching ad rules', () => {
  assert.equal(blocker.shouldBlock('https://ads.example.test/', 'mainFrame', 'https://example.test'), false);
  assert.equal(blocker.shouldBlock('https://cdn.example.test/movie.m3u8', 'media', 'https://example.test'), false);
});
test('domain-specific cosmetic rules are generated by ABP core', () => {
  assert.match(blocker.stylesheet('https://example.test/'), /\.advertisement/);
  assert.doesNotMatch(blocker.stylesheet('https://other.test/'), /\.advertisement/);
});
